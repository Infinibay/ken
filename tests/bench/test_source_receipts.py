import hashlib
import json

import pytest


def frozen(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src/engine.py").write_text("VERSION = 1\n")
    files = {"src/engine.py": hashlib.sha256((tmp_path / "src/engine.py").read_bytes()).hexdigest()}
    receipt = {"files": files, "tree_sha256": hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()}
    (tmp_path / "SOURCE-MANIFEST.json").write_text(json.dumps(receipt))
    return tmp_path


def test_source_receipt_verifies_actual_bytes_and_returns_receipt_hash(tmp_path):
    from ken.bench.source_receipts import verify_frozen_source
    root = frozen(tmp_path)
    assert verify_frozen_source(root) == hashlib.sha256((root / "SOURCE-MANIFEST.json").read_bytes()).hexdigest()
    (root / "src/engine.py").write_text("VERSION = 2\n")
    with pytest.raises(ValueError, match="source bytes"):
        verify_frozen_source(root)


def test_added_importable_source_cannot_hide_outside_the_frozen_inventory(tmp_path):
    from ken.bench.source_receipts import verify_frozen_source
    root = frozen(tmp_path)
    (root / "src/hidden.py").write_text("OVERRIDE = True\n")
    with pytest.raises(ValueError, match="inventory"):
        verify_frozen_source(root)


def test_bytecode_is_excluded_but_manifest_paths_cannot_escape_root(tmp_path):
    from ken.bench.source_receipts import verify_frozen_source
    root = frozen(tmp_path)
    (root / "src/__pycache__").mkdir()
    (root / "src/__pycache__/engine.pyc").write_bytes(b"generated bytecode")
    verify_frozen_source(root)
    receipt = json.loads((root / "SOURCE-MANIFEST.json").read_text())
    receipt["files"]["../outside.py"] = "a" * 64
    (root / "SOURCE-MANIFEST.json").write_text(json.dumps(receipt))
    with pytest.raises(ValueError, match="escape"):
        verify_frozen_source(root)
