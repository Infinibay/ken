async fn setup() -> Option<(PostgresStorage, WorkspaceId, Vec<(String, ChunkId)>)> {
    let url = std::env::var("DATABASE_URL").ok()?;
    let s = PostgresStorage::connect(&url).await.expect("connect");
    s.migrate().await.expect("migrate");
    let t = s
        .create_tenant("e2e-quality", PlanTier::Free)
        .await
        .expect("tenant");
    let w = s
        .create_workspace(t, "ws", WorkspaceSettings::default())
        .await
        .expect("workspace");
    let src = s
        .create_source(NewSource {
            workspace_id: w,
            kind: SourceKind::Manual,
            name: "manual".into(),
            config_json: serde_json::Value::Null,
            keep_history: false,
            default_acl: Acl::default(),
        })
        .await
        .expect("source");

    let embedder = FastEmbedder::nomic_v15().expect("fastembed init");
    let mut by_slug: Vec<(String, ChunkId)> = Vec::with_capacity(CORPUS.len());

    // Batch-embed all passages once — fastembed amortizes much better than
    // single calls because the ONNX session reuses input buffers.
    let passages: Vec<&str> = CORPUS.iter().map(|(_, p)| *p).collect();
    let vectors = embedder.embed_passages(&passages);
    assert_eq!(vectors.len(), CORPUS.len());

    for ((slug, text), vec) in CORPUS.iter().zip(vectors.into_iter()) {
        let did = s
            .upsert_document(NewDocument {
                workspace_id: w,
                source_id: src,
                external_id: Some((*slug).to_string()),
                kind: ContentKind::PlainText,
                mime: "text/plain".into(),
                title: Some((*slug).to_string()),
                path_or_url: None,
                content_hash: *blake3::hash(text.as_bytes()).as_bytes(),
                acl: Acl::default(),
                metadata: MetadataMap::default(),
                source_modified_at: None,
            })
            .await
            .unwrap()
            .current_id();
        let cids = s
            .replace_chunks(
                did,
                vec![NewChunk {
                    kind: ChunkKind::Paragraph,
                    position: ChunkPosition::ByteRange { start: 0, end: text.len() as u64 },
                    text: (*text).to_string(),
                    metadata: MetadataMap::default(),
                    embedding: None,
                }],
            )
            .await
            .unwrap();
        s.put_embedding(EmbedKey::chunk(cids[0]), vec).await.unwrap();
        by_slug.push(((*slug).to_string(), cids[0]));
    }
    Some((s, w, by_slug))
}

fn slug_for(by_slug: &[(String, ChunkId)], cid: ChunkId) -> Option<&str> {
    by_slug.iter().find(|(_, c)| *c == cid).map(|(s, _)| s.as_str())
}

fn fmt_topk(by_slug: &[(String, ChunkId)], result: &RankResult, k: usize) -> Vec<String> {
    result
        .items
        .iter()
        .take(k)
        .map(|it| {
            let label = match it.target {
                NodeRef::Chunk(c) => slug_for(by_slug, c).unwrap_or("?").to_string(),
                _ => format!("{:?}", it.target),
            };
            format!("{label}@{:.2}({})", it.score, it.reason)
        })
        .collect()
}

async fn run_query(
    s: &PostgresStorage,
    w: WorkspaceId,
    embedder: &FastEmbedder,
    query: &str,
) -> RankResult {
    let session = s.create_session(w, Some("e2e-quality")).await.unwrap();
    let ranker = Ranker::new(s);
    ranker
        .rank(RankRequest {
            workspace: w,
            session,
            query_embedding: embedder.embed_query(query),
            iteration: 0,
        })
        .await
}

fn topk_contains(
    result: &RankResult,
    by_slug: &[(String, ChunkId)],
    expected: &str,
    acceptable: &[&str],
    k: usize,
) -> bool {
    result.items.iter().take(k).any(|it| {
        if let NodeRef::Chunk(c) = it.target {
            let slug = slug_for(by_slug, c).unwrap_or("?");
            slug == expected || acceptable.contains(&slug)
        } else {
            false
        }
    })
}

// ============================================================================
// Per-query tests — each one is a mini regression guard.
// ============================================================================

const TOP_K: usize = 3;

async fn check_one_query(idx: usize) {
    let Some((s, w, by_slug)) = setup().await else { return };
    let embedder = FastEmbedder::nomic_v15().expect("fastembed init");
    let (name, query, expected, acceptable) = QUERIES[idx];
    let result = run_query(&s, w, &embedder, query).await;
    assert!(
        topk_contains(&result, &by_slug, expected, acceptable, TOP_K),
        "{name}: query={query:?} expected={expected:?} acceptable={acceptable:?}; \
         top-{TOP_K} = {:?}",
        fmt_topk(&by_slug, &result, TOP_K)
    );
}

