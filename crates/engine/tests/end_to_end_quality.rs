// ============================================================================
// Negative test: unrelated query should be filtered by the confidence gate.
// ============================================================================

#[tokio::test]
#[ignore]
async fn unrelated_query_is_rejected_by_confidence_gate() {
    let Some((s, w, by_slug)) = setup().await else { return };
    let embedder = FastEmbedder::nomic_v15().expect("fastembed init");
    let result = run_query(
        &s,
        w,
        &embedder,
        "what is the chemical composition of saturn's atmosphere",
    )
    .await;
    // Either empty (gate fired), OR every top-K item is below 0.5 cosine.
    // The gate's job is to prevent confident-looking nonsense — if it fired
    // we're done; if it didn't, the items must at least not be high-confidence.
    if !result.items.is_empty() {
        assert!(
            result.items[0].score < 0.5,
            "expected gate to reject or low confidence; got top {:?}",
            fmt_topk(&by_slug, &result, TOP_K)
        );
    }
}

// ============================================================================
// Aggregate hit-rate.
// ============================================================================

#[tokio::test]
#[ignore]
async fn aggregate_hit_rate_at_least_5_of_6() {
    let Some((s, w, by_slug)) = setup().await else { return };
    let embedder = FastEmbedder::nomic_v15().expect("fastembed init");
    let mut hits = 0usize;
    let mut report: Vec<String> = Vec::new();
    for (name, query, expected, acceptable) in QUERIES {
        let result = run_query(&s, w, &embedder, query).await;
        let ok = topk_contains(&result, &by_slug, expected, acceptable, TOP_K);
        if ok {
            hits += 1;
        } else {
            report.push(format!(
                "{name}: query={query:?} expected={expected:?} top={:?}",
                fmt_topk(&by_slug, &result, TOP_K)
            ));
        }
    }
    assert!(
        hits >= QUERIES.len() - 1,
        "hit-rate {hits}/{} (≥{} required); misses:\n{}",
        QUERIES.len(),
        QUERIES.len() - 1,
        report.join("\n")
    );
}
