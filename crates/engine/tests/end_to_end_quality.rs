//! End-to-end retrieval quality test on a small handcrafted corpus, using
//! real fastembed embeddings + real Postgres + the full ranker. This is the
//! integration-level regression guard for retrieval quality (cf. infinidev's
//! `test_context_rank_benchmark.py`).
//!
//! Each query asserts a specific expected chunk surfaces in top-K. Tests are
//! split per query so a regression points at exactly which scenario broke
//! (vs. one monolithic test reporting "4/6 passed"). A query-level hit-rate
//! sanity check is bundled at the end.
//!
//! Why a tiny corpus (10 chunks): with real embeddings and the default
//! confidence gate we only need a handful of chunks for the test to be
//! informative — adding noise chunks doesn't change the calibration story
//! and only inflates test time. The synthetic ranker test in
//! `ranker_quality.rs` is the place to test merge / MAD shape; this file
//! is the place to test calibration.
//!
//! Run with:
//!     DATABASE_URL=postgres://cae:cae_dev@localhost:5432/context_engine \
//!     cargo test -p cae-engine --features "postgres fastembed" \
//!         --test end_to_end_quality -- --ignored

